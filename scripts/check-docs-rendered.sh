#!/usr/bin/env bash
# Assert that markup the SOURCE clearly intends was actually consumed by the build.
#
# This is the check that found #2081, and nothing else would have. Reading mkdocs.yml told us
# "no markdown_extensions configured"; only grepping the built HTML showed what that cost
# readers: 33 GitHub alert markers printed as literal "[!WARNING]" text inside ordinary
# blockquotes, and every architecture diagram rendered as a wall of code.
#
# Asserts the CLASS, not the instances: no alert marker of any type may survive anywhere, and
# no mermaid block may render as code anywhere. Adding a sixth alert type or a tenth diagram
# needs no change here.
#
# Takes the built site directory (default _site, which is what CI builds).
set -euo pipefail

SITE="${1:-_site}"
SITE="${SITE%/}"   # `site/` would otherwise leave paths that never match "$SITE/404.html"

if [ ! -d "$SITE" ]; then
  echo "[NO-SCAN] '$SITE' is not a directory -- nothing was checked."
  echo "  Build the site first: mkdocs build --site-dir $SITE --strict"
  exit 1
fi

pages=$(find "$SITE" -name '*.html' | wc -l | tr -d ' ')
if [ "$pages" -lt 5 ]; then
  echo "[NO-SCAN] only $pages HTML page(s) under '$SITE'. That is too few to be a real build,"
  echo "  and a near-empty directory would pass every assertion below."
  exit 1
fi

fail=0

# GitHub alert syntax. Native on github.com, unknown to Python-Markdown: without the build-time
# conversion these reach the reader as text.
# `|| true` is load-bearing: grep exits 1 when it finds nothing, which under `set -e` with
# `pipefail` is exactly the HEALTHY case. Without it this guard aborted, silently, on a clean
# build -- failing CI on correct documentation and reporting nothing at all.
markers=$(grep -rho '\[!\(NOTE\|IMPORTANT\|TIP\|WARNING\|CAUTION\)\]' "$SITE" --include='*.html' | wc -l | tr -d ' ' || true)
if [ "$markers" -ne 0 ]; then
  echo "[LEAKED-ALERT] $markers GitHub alert marker(s) are visible to readers as literal text."
  echo "  They render inside an ordinary blockquote instead of a callout, so the warnings that"
  echo "  matter most read as ordinary prose. Pages affected:"
  grep -rl '\[!\(NOTE\|IMPORTANT\|TIP\|WARNING\|CAUTION\)\]' "$SITE" --include='*.html' | sed "s|^$SITE/|    |" || true
  fail=1
fi

# Mermaid handed to the syntax highlighter instead of to mermaid.js.
diagrams=$(grep -rho 'class="language-mermaid"' "$SITE" --include='*.html' | wc -l | tr -d ' ' || true)
if [ "$diagrams" -ne 0 ]; then
  echo "[UNRENDERED-DIAGRAM] $diagrams mermaid block(s) rendered as a code block."
  echo "  Readers get the diagram's source text instead of the diagram. Pages affected:"
  grep -rl 'class="language-mermaid"' "$SITE" --include='*.html' | sed "s|^$SITE/|    |" || true
  fail=1
fi

# Search Console ownership token (overrides/main.html, extra.google_site_verification). The
# template renders it only when set, so deleting the key keeps the build green -- and Google,
# which re-checks periodically, would quietly unverify the property (#2381).
unverified=$(grep -rL 'name="google-site-verification"' "$SITE" --include='*.html' || true)
if [ -n "$unverified" ]; then
  echo "[MISSING-VERIFICATION] $(echo "$unverified" | wc -l | tr -d ' ') page(s) lack the google-site-verification meta tag."
  echo "  Check extra.google_site_verification in mkdocs.yml and overrides/main.html. Pages affected:"
  echo "$unverified" | sed "s|^$SITE/|    |"
  fail=1
fi

# Review footer. The About page (docs/about.md) tells readers that every page shows when it was
# last updated and last reviewed; this is what holds the site to that (#2383). The source-side
# check (check_docs_review.py --changed-files) proves the footer is in the markdown, not that it
# reached the page. 404.html is generated by the theme and has no source page.
#
# Matched as the markup a real footer renders to -- one paragraph of two <em> -- not as bare
# text, because bare text is satisfied by footers no reader sees: one inside an HTML comment
# (copied through verbatim, asterisks and all) or an example in a code block (rendered as
# <span class="ge">). Both passed the first version of this check.
DATE='[0-9]{4}-[0-9]{2}-[0-9]{2}'
undated=$(find "$SITE" -name '*.html' ! -path "$SITE/404.html" -print0 \
  | xargs -0 grep -LE "<p><em>Last Updated: ?$DATE</em> \\| <em>Last Reviewed: ?$DATE</em></p>" || true)
if [ -n "$undated" ]; then
  echo "[UNDATED-PAGE] $(echo "$undated" | wc -l | tr -d ' ') page(s) do not show their Last Updated / Last Reviewed dates."
  echo "  The About page promises every page does. Add the footer from .agents/skills/global-docs/SKILL.md. Pages affected:"
  echo "$undated" | sed "s|^$SITE/|    |"
  fail=1
fi

# Community-project notice on the site's home page (#2385). check-docs-routing.py holds the
# markdown; this holds what readers get: a callout, above the first section heading. The source
# writes it as a GitHub alert, so a broken alerts hook would print it as a plain blockquote with
# a literal "[!IMPORTANT]" -- which the leaked-marker check above would also report.
home="$SITE/index.html"
above=""
page=""
if [ -f "$home" ]; then
  # Cut at the first "<h2" itself, not at the line holding it: HTML need not break lines, and a
  # minified page would otherwise leave nothing above the heading -- or, cut by line, everything.
  page=$(cat "$home")
  above=${page%%<h2*}
fi
# Inside the callout, not merely beside one: an unrelated admonition above a plain-paragraph
# notice satisfied two separate greps. Take the text from the first admonition to its first
# </div> -- the converted alert is a single div holding two paragraphs -- and look there.
notice_ok=0
case "$page" in *"<h2"*) ;; *) above="" ;; esac   # no section heading: nothing is "above" one
case "$above" in
  *'class="admonition'*)
    callout=${above#*class=\"admonition}
    callout=${callout%%</div>*}
    if grep -q '<strong>Community project</strong> — not an official Liferay product and not covered by Liferay Support' <<<"$callout"; then
      notice_ok=1
    fi
    ;;
esac
if [ "$notice_ok" -ne 1 ]; then
  echo "[NO-NOTICE] the home page does not show the community-project notice as a callout above its first section."
  echo "  Readers must see that this is not an official Liferay product before they decide to adopt it."
  echo "  Source: the [!IMPORTANT] alert straight after the opening paragraph of docs/README.md."
  fail=1
fi

if [ "$fail" -ne 0 ]; then
  echo
  echo "❌ The published output does not match what the source asks for."
  exit 1
fi

echo "✅ $pages page(s): no alert markers leaked, no mermaid rendered as code, verification tag and review dates on every page, community notice on the home page."
